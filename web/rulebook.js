  /**
   * 两端共用渲染器（桌面 #modal-root 与手机 #m-modal 都调它，避免各写一份）。
   * @param {HTMLElement} host 承接内容的容器
   * @returns {void}
   */
  function render(host) {
    const d = root.document;
    if (!host || !d) return;
    host.innerHTML = '';
    const nav = d.createElement('div');
    nav.className = 'rb-nav';
    const body = d.createElement('div');
    body.className = 'rb-body';
    SECTIONS.forEach((sec, i) => {
      const chip = d.createElement('button');
      chip.className = 'rb-chip';
      chip.type = 'button';
      chip.textContent = `${i + 1}. ${sec.title}`;
      chip.addEventListener('click', () => {
        const t = d.getElementById(`rb-${sec.id}`);
        if (t && t.scrollIntoView) t.scrollIntoView({ block: 'start', behavior: 'smooth' });
      });
      nav.appendChild(chip);

      const card = d.createElement('section');
      card.className = 'rb-sec';
      card.id = `rb-${sec.id}`;
      const h = d.createElement('h3');
      h.className = 'rb-h';
      h.textContent = `${i + 1}. ${sec.title}`;
      card.appendChild(h);
      for (const b of sec.blocks) card.appendChild(blockEl(d, b));
      body.appendChild(card);
    });
    host.append(nav, body);
  }

  /** 单个内容块 → DOM（table 一律套横向滚动壳：390px 屏幕上 4 列表格必然超宽） */
  function blockEl(d, b) {
    if (!b || !b.t) return d.createElement('div');
    if (b.t === 'p') {
      const p = d.createElement('p');
      p.className = 'rb-p';
      p.textContent = b.text || '';
      return p;
    }
    if (b.t === 'note') {
      const n = d.createElement('p');
      n.className = 'rb-note';
      n.textContent = b.text || '';
      return n;
    }
    if (b.t === 'steps' || b.t === 'ul') {
      const l = d.createElement(b.t === 'steps' ? 'ol' : 'ul');
      l.className = b.t === 'steps' ? 'rb-steps' : 'rb-ul';
      for (const it of b.items || []) {
        const li = d.createElement('li');
        li.textContent = it;
        l.appendChild(li);
      }
      return l;
    }
    if (b.t === 'table') {
      const wrap = d.createElement('div');
      wrap.className = 'rb-tw';
      const t = d.createElement('table');
      t.className = 'rb-table';
      const thead = d.createElement('thead');
      const hr = d.createElement('tr');
      for (const h of b.head || []) {
        const th = d.createElement('th');
        th.textContent = h;
        hr.appendChild(th);
      }
      thead.appendChild(hr);
      t.appendChild(thead);
      const tb = d.createElement('tbody');
      for (const row of b.rows || []) {
        const tr = d.createElement('tr');
        for (const c of row) {
          const td = d.createElement('td');
          td.textContent = c == null ? '' : String(c);
          tr.appendChild(td);
        }
        tb.appendChild(tr);
      }
      t.appendChild(tb);
      wrap.appendChild(t);
      return wrap;
    }
    const p = d.createElement('p');
    p.className = 'rb-p';
    p.textContent = b.text || '';
    return p;
  }

  const api = { SECTIONS, render };

  root.Rulebook = api;
